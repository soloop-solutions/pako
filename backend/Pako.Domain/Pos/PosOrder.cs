namespace Pako.Domain.Pos;

// docs/POS_PLAN.md §12.4 (D5) — a sale at the till. Not an Invoice: it may be anonymous, it posts
// through its session (D6), and it is fiscalized as a coupon. A business buyer asking for a tax
// invoice gets one linked here (InvoiceId).
public enum PosOrderKind
{
    Sale,
    // A return of lines from an earlier order (ATK coupon type Return).
    Return,
    // Cancels a whole earlier order (ATK coupon type Cancel).
    Cancel,
}

public enum PosOrderState
{
    Paid,
    // A cancellation coupon reversed it.
    Cancelled,
}

public class PosOrder
{
    public Guid Id { get; set; }
    public Guid CompanyId { get; set; }
    // Generated by the till; makes offline sync idempotent (D11).
    public Guid ClientUuid { get; set; }
    public Guid SessionId { get; set; }
    public Guid RegisterId { get; set; }
    public Guid StoreId { get; set; }
    public PosOrderKind Kind { get; set; } = PosOrderKind.Sale;
    public PosOrderState State { get; set; } = PosOrderState.Paid;
    // "S3-0042": register code and its running order number.
    public string Number { get; set; } = string.Empty;
    public DateTime OrderedAt { get; set; }
    public Guid OperatorUserId { get; set; }
    public string OperatorName { get; set; } = string.Empty;
    public Guid? CustomerId { get; set; }
    // Return/cancel: the order it reverses.
    public Guid? OriginalOrderId { get; set; }
    public string? Reason { get; set; }
    // A tax invoice issued for a business buyer (AI 01/2026 Art. 5(3)).
    public Guid? InvoiceId { get; set; }
    // Gross (VAT-inclusive) totals; signed positive for every kind — the kind gives the direction.
    public decimal Total { get; set; }
    public decimal TotalTax { get; set; }
    public decimal TotalDiscount { get; set; }
    public bool CreatedOffline { get; set; }
    // P2: coupon codes entered, the loyalty card shown, points it earned (negative on returns) and
    // points redeemed as a discount.
    public string? CouponCodes { get; set; }
    public Guid? LoyaltyCardId { get; set; }
    // P3: the tab this order pays (all or part of).
    public Guid? TabId { get; set; }
    // P4: the appointment or repair this sale settles.
    public Guid? AppointmentId { get; set; }
    public Guid? RepairTicketId { get; set; }
    // P7: the prescription dispensed, the fleet card charged, the online order fiscalised.
    public Guid? PrescriptionId { get; set; }
    public Guid? FleetCardId { get; set; }
    public Guid? ChannelOrderId { get; set; }
    public decimal PointsEarned { get; set; }
    public decimal PointsRedeemed { get; set; }
    public DateTime ReceivedAt { get; set; } = DateTime.UtcNow;
    public List<PosOrderLine> Lines { get; set; } = new();
    public List<PosPayment> Payments { get; set; } = new();
}

public class PosOrderLine
{
    public Guid Id { get; set; }
    public Guid OrderId { get; set; }
    public int LineNo { get; set; }
    public Guid? ItemId { get; set; }
    public string Description { get; set; } = string.Empty;
    public string Unit { get; set; } = string.Empty;
    public decimal Quantity { get; set; }
    public decimal UnitFactor { get; set; } = 1m;
    // VAT-inclusive price per unit before discount.
    public decimal UnitPrice { get; set; }
    public decimal DiscountAmount { get; set; }
    public Guid? TaxDefinitionId { get; set; }
    public string TaxLetter { get; set; } = string.Empty;
    public decimal TaxRate { get; set; }
    // What the customer pays for the line (VAT-inclusive, after discount), its net and its VAT.
    public decimal Gross { get; set; }
    public decimal Net { get; set; }
    public decimal Tax { get; set; }
    public Guid RevenueAccountId { get; set; }
    public string? LotNumber { get; set; }
    // P2: the cashier confirmed the buyer's age for an age-restricted item.
    public bool AgeVerified { get; set; }
    // P2: the part of DiscountAmount a promotion, coupon or loyalty redemption gave (the rest was
    // typed by the cashier), and which program gave it.
    public decimal ProgramDiscount { get; set; }
    public Guid? ProgramId { get; set; }
    // P2: a gift card sold on this line (no item; its amount loads the card).
    public string? GiftCardNumber { get; set; }
    // P2: the serial number (IMEI) of the unit sold, for items that track serials.
    public string? SerialNumber { get; set; }
    // P3: the tab line this pays (part of).
    public Guid? TabLineId { get; set; }
    // P3: the modifiers chosen (comma-separated ids), for their recipe changes.
    public string? ModifierIds { get; set; }
    // P4: who performed the service (commission), and the package or membership the line uses or sells.
    public Guid? StaffUserId { get; set; }
    public string? PackageNumber { get; set; }
    public string? MembershipNumber { get; set; }
    // P7: the prescription line dispensed; the fuel nozzle that pumped it.
    public Guid? PrescriptionLineId { get; set; }
    public Guid? NozzleId { get; set; }
    // P7 agency items: the principal owed this line, and the commission kept (VAT-inclusive).
    public Guid? AgencyPartnerId { get; set; }
    public decimal AgencyCommission { get; set; }
    // Return lines: the sold line they give back.
    public Guid? OriginalLineId { get; set; }
    // The stock this line moved, as valued when the order was recorded: what the session posts to
    // cost of goods sold. A later back-dated document that revalues the move books its own
    // difference, so the session must not read the move's current value (it would count it twice).
    public decimal CostValue { get; set; }
    public decimal CostCorrection { get; set; }
    // Cost of goods sold already booked by later documents that changed when this (back-dated,
    // offline) order replayed the stock ledger (D11), for this line's item.
    public decimal CostReplay { get; set; }
    public PosOrder? Order { get; set; }
}

public class PosPayment
{
    public Guid Id { get; set; }
    public Guid OrderId { get; set; }
    public Guid PaymentMethodId { get; set; }
    // What the tender settled (cash: after change).
    public decimal Amount { get; set; }
    // Cash: what the customer handed over; the difference to Amount (and Tip) is change.
    public decimal? Tendered { get; set; }
    public string? Reference { get; set; }
    // P3: a tip paid with this tender, on top of Amount — the staff's money, not revenue, and not
    // on the fiscal coupon.
    public decimal Tip { get; set; }
    // P7: an on-account tender charged to someone other than the customer — a prescription's payer,
    // a fleet card's company, the courier collecting cash on delivery.
    public Guid? PartnerId { get; set; }
    public PosOrder? Order { get; set; }
}

import { useState, type FormEvent } from "react";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import type { SaleContractResponse, SaveSaleContractRequest } from "@pako/shared";
import { Plus, X } from "lucide-react";

import { apiClient, getApiErrorMessage } from "@/api/client";
import { FormDialog } from "@/components/shared/FormDialog";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Select } from "@/components/ui/select";
import { Textarea } from "@/components/ui/textarea";
import { useCompany } from "@/context/CompanyContext";
import { vxKeys } from "@/hooks/useVerticals";
import { isoToday } from "@/lib/sales-order-enums";
import { cn } from "@/lib/utils";
import { ContractKind } from "@/lib/verticals-enums";
import { ErrorAlert, Field, PartnerField } from "@/pages/verticals/shared";
import { gridKeyDown, parseNum, useT } from "@/pages/verticals/verticals-utils";

interface PlanRow { dueDate: string; amount: string }
const emptyRow = (): PlanRow => ({ dueDate: "", amount: "" });

// docs/ERP_VERTICALS_PLAN.md §2 — a sale contract (kontratë shitjeje) for one unit, with its
// payment plan: either typed as rows, or generated by the API from a down payment and a number of
// monthly installments (këste). The plan must add up to the price; the API says so if it doesn't.
export function SaleContractDialog({ unit, reservation, onClose, onSaved }: {
  unit: { id: string; number: string; buildingName: string; listPrice: number };
  reservation?: { id: string; partnerId: string; partnerName?: string };
  onClose: () => void;
  onSaved: (c: SaleContractResponse) => void;
}) {
  const t = useT();
  const queryClient = useQueryClient();
  const { activeCompanyId } = useCompany();
  const [buyerPartnerId, setBuyer] = useState(reservation?.partnerId ?? "");
  const [contractDate, setContractDate] = useState(isoToday());
  const [price, setPrice] = useState(String(unit.listPrice));
  const [kind, setKind] = useState<number>(ContractKind.Sale);
  const [mode, setMode] = useState<"generate" | "rows">("generate");
  const [downPayment, setDownPayment] = useState("");
  const [installmentCount, setInstallmentCount] = useState("");
  const [firstInstallment, setFirstInstallment] = useState("");
  const [rows, setRows] = useState<PlanRow[]>([emptyRow()]);
  const [notes, setNotes] = useState("");
  const [error, setError] = useState<string | null>(null);

  function request(): SaveSaleContractRequest {
    const base: SaveSaleContractRequest = {
      unitId: unit.id,
      buyerPartnerId,
      contractDate,
      price: parseNum(price) || 0,
      kind,
      reservationId: reservation?.id,
      notes: notes.trim() || undefined,
    };
    if (mode === "rows") {
      return { ...base, installments: rows.filter((r) => r.dueDate && r.amount).map((r) => ({ dueDate: r.dueDate, amount: parseNum(r.amount) || 0 })) };
    }
    return {
      ...base,
      downPayment: parseNum(downPayment) || 0,
      installmentCount: Number(installmentCount) || 0,
      firstInstallment: firstInstallment || undefined,
    };
  }

  const save = useMutation({
    mutationFn: () => apiClient.createUnitSaleContract(activeCompanyId as string, request()),
    onSuccess: async (saved) => {
      await queryClient.invalidateQueries({ queryKey: vxKeys.units(activeCompanyId) });
      await queryClient.invalidateQueries({ queryKey: vxKeys.buildings(activeCompanyId) });
      await queryClient.invalidateQueries({ queryKey: vxKeys.contracts(activeCompanyId) });
      await queryClient.invalidateQueries({ queryKey: vxKeys.reservations(activeCompanyId) });
      onSaved(saved);
    },
    onError: (err: unknown) => setError(getApiErrorMessage(err, t("vx.contract.saveError"))),
  });

  function submit(e: FormEvent) {
    e.preventDefault();
    setError(null);
    if (!buyerPartnerId) return setError(t("vx.contract.buyerRequired"));
    save.mutate();
  }
  const setRow = (i: number, patch: Partial<PlanRow>) => setRows((rs) => rs.map((r, j) => (j === i ? { ...r, ...patch } : r)));

  return (
    <FormDialog open onOpenChange={(o) => !o && onClose()} title={t("vx.contract.newFor", { unit: `${unit.buildingName} · ${unit.number}` })} size="md">
      <form className="flex flex-col gap-3" onSubmit={submit}>
        <ErrorAlert error={error} />
        <div className="grid gap-3 sm:grid-cols-2">
          <PartnerField id="sc-buyer" label={t("vx.contract.buyer")} role="customer" value={buyerPartnerId} onChange={setBuyer} fallbackLabel={reservation?.partnerName} />
          <Field id="sc-kind" label={t("vx.contract.kind")}>
            <Select id="sc-kind" value={String(kind)} onValueChange={(v) => setKind(Number(v))}
              options={[ContractKind.Sale, ContractKind.Compensation].map((k) => ({ value: String(k), label: t(`vx.contractKind.${k}`) }))} />
          </Field>
          <Field id="sc-date" label={t("vx.contract.date")}>
            <Input id="sc-date" type="date" required value={contractDate} onChange={(e) => setContractDate(e.target.value)} />
          </Field>
          <Field id="sc-price" label={t("vx.contract.price")} hint={t("vx.vatIncluded")}>
            <Input id="sc-price" inputMode="decimal" className="text-right tnum" required value={price} onChange={(e) => setPrice(e.target.value)} />
          </Field>
        </div>
        <fieldset className="flex flex-col gap-2 rounded-md border p-3">
          <legend className="px-1 text-sm font-medium">{t("vx.contract.plan")}</legend>
          <div className="inline-flex w-fit rounded-md border bg-card p-0.5" role="radiogroup" aria-label={t("vx.contract.plan")}>
            {(["generate", "rows"] as const).map((m) => (
              <button key={m} type="button" role="radio" aria-checked={mode === m} onClick={() => setMode(m)}
                className={cn("h-7 rounded-[5px] px-3 text-[12.5px] font-medium", mode === m ? "bg-primary text-primary-foreground" : "text-muted-foreground hover:bg-accent")}>
                {t(`vx.contract.plan.${m}`)}
              </button>
            ))}
          </div>
          {mode === "generate" ? (
            <div className="grid gap-3 sm:grid-cols-3">
              <Field id="sc-down" label={t("vx.contract.downPayment")}>
                <Input id="sc-down" inputMode="decimal" className="text-right tnum" value={downPayment} onChange={(e) => setDownPayment(e.target.value)} />
              </Field>
              <Field id="sc-count" label={t("vx.contract.installmentCount")}>
                <Input id="sc-count" inputMode="numeric" className="text-right tnum" value={installmentCount} onChange={(e) => setInstallmentCount(e.target.value)} />
              </Field>
              <Field id="sc-first" label={t("vx.contract.firstInstallment")} hint={t("vx.contract.firstInstallmentHint")}>
                <Input id="sc-first" type="date" value={firstInstallment} onChange={(e) => setFirstInstallment(e.target.value)} />
              </Field>
            </div>
          ) : (
            <div className="flex flex-col gap-1" data-edit-grid>
              <div className="grid grid-cols-[2rem_10rem_9rem_2.25rem] gap-2 text-xs font-medium text-muted-foreground">
                <span>#</span><span>{t("vx.contract.dueDate")}</span><span className="text-right">{t("common.amount")}</span><span />
              </div>
              {rows.map((r, i) => (
                <div key={i} className="grid grid-cols-[2rem_10rem_9rem_2.25rem] items-center gap-2" data-testid="plan-row">
                  <span className="text-sm text-muted-foreground">{i + 1}</span>
                  <Input type="date" className="h-7" aria-label={t("vx.contract.dueDate")} value={r.dueDate} onChange={(e) => setRow(i, { dueDate: e.target.value })} />
                  <Input className="h-7 text-right tnum" inputMode="decimal" aria-label={t("common.amount")} value={r.amount}
                    data-row={i} data-col="amount" onKeyDown={gridKeyDown} onChange={(e) => setRow(i, { amount: e.target.value })} />
                  <Button type="button" size="icon" variant="ghost" className="size-7" aria-label={t("common.remove")}
                    onClick={() => setRows((rs) => (rs.length > 1 ? rs.filter((_, j) => j !== i) : [emptyRow()]))}>
                    <X className="size-3.5" />
                  </Button>
                </div>
              ))}
              <Button type="button" size="xs" variant="ghost" className="w-fit" onClick={() => setRows((rs) => [...rs, emptyRow()])}>
                <Plus className="size-3.5" />{t("vx.contract.addInstallment")}
              </Button>
            </div>
          )}
          <p className="text-[11px] text-muted-foreground">{t("vx.contract.planHint")}</p>
        </fieldset>
        <Field id="sc-notes" label={t("vx.notes")}>
          <Textarea id="sc-notes" value={notes} onChange={(e) => setNotes(e.target.value)} />
        </Field>
        <div className="flex justify-end gap-2">
          <Button type="button" variant="outline" onClick={onClose}>{t("common.cancel")}</Button>
          <Button type="submit" disabled={save.isPending}>{t("vx.contract.create")}</Button>
        </div>
      </form>
    </FormDialog>
  );
}
